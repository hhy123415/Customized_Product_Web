-- 积分记录表（通用版）
CREATE TABLE point_records (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    points_change INTEGER NOT NULL,          -- 变动数值，正数=获得，负数=消费/扣减
    points_after INTEGER NOT NULL,           -- 变动后的账户余额，用于快速对账
    detail VARCHAR(255) NOT NULL DEFAULT '', -- 变动原因描述，如“签到”“购买枫木前节”
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- 约束
    CONSTRAINT chk_points_change_nonzero CHECK (points_change <> 0),
    CONSTRAINT chk_points_after_non_negative CHECK (points_after >= 0),

    -- 外键：保护审计记录，不允许删除仍有积分记录的用户
    CONSTRAINT fk_point_records_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 索引
CREATE INDEX idx_point_records_user_id ON point_records(user_id);
CREATE INDEX idx_point_records_created_at ON point_records(created_at DESC);
CREATE INDEX idx_point_records_detail ON point_records(detail);   -- 方便按原因筛选

CREATE OR REPLACE FUNCTION sync_user_points_on_point_record()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE users SET points = NEW.points_after WHERE user_id = NEW.user_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_point_records_sync_points
AFTER INSERT ON point_records
FOR EACH ROW
EXECUTE FUNCTION sync_user_points_on_point_record();